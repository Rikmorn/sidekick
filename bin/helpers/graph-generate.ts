/**
 * ops-4 — the two committed generated surfaces: `docs/STATE.md` and `MAP.md`.
 *
 * Both are derived views of the same graph, rendered for different readers:
 * STATE answers "where are we right now", MAP answers "what is in this repo and
 * where". They are the deliberate exception to never committing derived files,
 * because both must exist on a fresh clone before any tool has run — and a
 * stale one fails lint like a broken pin.
 *
 * Output is deterministic: stable ordering, counts and pointers rather than
 * prose, and no timestamp anywhere except the commit the build read.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { collectGraph } from './graph-build.js';
import { collectSourceLint, lintSummary } from './graph-lint.js';
import type { Entity } from './graph-model.js';
import type { GraphSnapshot, RunRow } from './graph-store.js';

export const STATE_PATH = 'docs/STATE.md';
export const MAP_PATH = 'MAP.md';

const STAMP_PREFIX = '**Built at commit:**';

/**
 * Blank the commit stamp so drift comparison sees content only.
 *
 * Without this the stamp guarantees drift on the very next commit, and a check
 * that always fires teaches everyone to ignore it. The stamp still records what
 * the file was generated from; it just is not what "drifted" means.
 */
export function normalizeForDrift(text: string): string {
  return text
    .split('\n')
    .map((line) => (line.startsWith(STAMP_PREFIX) ? STAMP_PREFIX : line))
    .join('\n');
}

function stamp(snapshot: GraphSnapshot): string {
  return `${STAMP_PREFIX} \`${snapshot.meta.built_at_commit ?? 'unknown'}\``;
}

const byId = (a: Entity, b: Entity): number => (a.id < b.id ? -1 : 1);

function entitiesOf(snapshot: GraphSnapshot, kind: string): Entity[] {
  return snapshot.entities.filter((e) => e.kind === kind).sort(byId);
}

/** Work items belonging to an epic, in ID order. */
function itemsOfEpic(snapshot: GraphSnapshot, epicId: string): Entity[] {
  return snapshot.entities
    .filter(
      (e) =>
        e.kind === 'item' &&
        (e.data as { epic?: string } | undefined)?.epic === epicId,
    )
    .sort(byId);
}

// ---- STATE.md ---------------------------------------------------------------

export interface StateInputs {
  snapshot: GraphSnapshot;
  lint: { errors: number; advisories: number };
}

/**
 * The current-state rollup. Completed items drop out by construction — their
 * story lives in their own record, and keeping them here is what turns a status
 * file into an unbounded log.
 */
export function generateState(inputs: StateInputs): string {
  const { snapshot, lint } = inputs;
  const lines: string[] = [
    '# STATE — where the project is right now',
    '',
    '<!-- Generated by `sidekick graph state`. Do not edit by hand: regenerate. -->',
    '<!-- Current state only. The timeline lives in `git log -p docs/STATE.md`. -->',
    '',
    stamp(snapshot),
    '',
  ];

  const epics = entitiesOf(snapshot, 'epic').filter(
    (e) => e.status !== 'done' && e.status !== 'closed',
  );
  lines.push(`## Open epics (${epics.length})`, '');
  if (epics.length === 0) {
    lines.push('None.', '');
  } else {
    lines.push(
      '| Epic | Done | Active | Open | Spec |',
      '|---|---|---|---|---|',
    );
    for (const epic of epics) {
      const items = itemsOfEpic(snapshot, epic.id);
      const done = items.filter((i) => i.status === 'done');
      const active = items.filter((i) => i.status === 'active');
      const open = items.filter((i) => i.status === 'open');
      lines.push(
        `| \`${epic.id}\` — ${epic.title} | ${done.length}/${items.length} | ${names(active)} | ${names(open)} | [spec](${epic.path ?? ''}) |`,
      );
    }
    lines.push('');
  }

  const active = snapshot.entities
    .filter((e) => e.kind === 'item' && e.status === 'active')
    .sort(byId);
  lines.push(`## Active items (${active.length})`, '');
  if (active.length === 0) {
    lines.push('None.', '');
  } else {
    for (const item of active) {
      lines.push(
        `- \`${item.id}\` — ${item.title} → [${item.path}](${item.path})`,
      );
    }
    lines.push('');
  }

  // The platform monolith still carries the roadmap, so it gets counts too.
  const platItems = snapshot.entities
    .filter((e) => e.id.startsWith('plat-'))
    .sort(byId);
  if (platItems.length > 0) {
    const openPlat = platItems.filter((e) => e.status !== 'done');
    lines.push(
      `## Platform roadmap ([EPIC.md](docs/EPIC.md))`,
      '',
      `${platItems.length - openPlat.length}/${platItems.length} items done · ${openPlat.length} open: ${openPlat
        .map((e) => `\`${e.id.replace('plat-', '')}\``)
        .join(', ')}`,
      '',
    );
  }

  const backlog = entitiesOf(snapshot, 'backlog');
  const openBacklog = backlog.filter((b) => b.status !== 'resolved');
  lines.push(
    '## Backlog',
    '',
    `${openBacklog.length} open of ${backlog.length} → [docs/backlog/](docs/backlog/)`,
    '',
  );

  lines.push('## Bench', '', ...benchLines(snapshot.runs), '');

  const proposed = entitiesOf(snapshot, 'adr').filter(
    (a) => a.status === 'Proposed',
  );
  lines.push(
    '## Freshness',
    '',
    `- Graph lint: ${lint.errors} error(s), ${lint.advisories} advisory finding(s)`,
    `- Decisions awaiting sign-off: ${proposed.length === 0 ? 'none' : proposed.map((a) => `\`${a.id}\``).join(', ')}`,
    `- Entities ${snapshot.entities.length} · edges ${snapshot.edges.length} · rebuild with \`sidekick graph build\``,
    '',
  );

  return `${lines.join('\n').trimEnd()}\n`;
}

function names(items: Entity[]): string {
  return items.length === 0 ? '—' : items.map((i) => `\`${i.id}\``).join(', ');
}

/**
 * Latest run against the one before it. With a single run set there is nothing
 * to compare to, and saying so beats implying a trend from one point.
 */
function benchLines(runs: RunRow[]): string[] {
  if (runs.length === 0) {
    return ['No run records in committed content.'];
  }
  const byRun = new Map<string, RunRow[]>();
  for (const run of runs) {
    byRun.set(run.run_id, [...(byRun.get(run.run_id) ?? []), run]);
  }
  const runIds = [...byRun.keys()].sort();
  const latest = runIds[runIds.length - 1];
  const rows = byRun.get(latest) ?? [];
  const pass = rows.filter((r) => r.verdict === 'pass').length;
  const fail = rows.filter((r) => r.verdict === 'fail').length;
  const suites = [...new Set(rows.map((r) => r.suite))].sort();

  const out = [
    `Latest run \`${latest}\`: ${rows.length} record(s), ${pass} pass, ${fail} fail across ${suites.length} suite(s) (${suites.join(', ')}).`,
  ];
  if (runIds.length > 1) {
    const prev = byRun.get(runIds[runIds.length - 2]) ?? [];
    const prevPass = prev.filter((r) => r.verdict === 'pass').length;
    out.push(
      `Previous run \`${runIds[runIds.length - 2]}\`: ${prevPass}/${prev.length} pass.`,
    );
  } else {
    out.push('This is the only committed run set — no baseline to compare to.');
  }
  return out;
}

// ---- MAP.md -----------------------------------------------------------------

export interface TaxonomyRow {
  folder: string;
  meaning: string;
  lifecycle: string;
}

/**
 * Read the folder table out of `docs/README.md` so the map states the taxonomy
 * that is actually decided, rather than a copy that can quietly disagree with it.
 */
export function parseTaxonomy(readme: string): TaxonomyRow[] {
  const rows: TaxonomyRow[] = [];
  for (const line of readme.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('|')) continue;
    const cells = trimmed
      .slice(1, trimmed.endsWith('|') ? -1 : undefined)
      .split(/(?<!\\)\|/)
      .map((c) => c.trim());
    if (cells.length < 3) continue;
    const folder = cells[0];
    if (/^-+:?$/.test(folder) || /^folder$/i.test(folder)) continue;
    if (!/`|\]\(/.test(folder)) continue;
    rows.push({
      folder: stripLink(folder),
      meaning: firstSentence(stripLink(cells[1])),
      lifecycle: firstSentence(stripLink(cells[2])),
    });
  }
  return rows;
}

function stripLink(cell: string): string {
  return cell
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*]/g, '')
    .trim();
}

/**
 * One clause of an authored table cell, for a map that has to stay scannable.
 * Cuts at a real boundary, truncates on a word, and closes a parenthesis it
 * opened — a one-liner that ends mid-bracket reads as corruption, not brevity.
 */
function firstSentence(text: string, max = 140): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  const stop = /\.\s|;\s| — /.exec(flat);
  let head = (stop ? flat.slice(0, stop.index) : flat).trim();
  if (head === '') head = flat;
  if (head.length > max) {
    const cut = head.slice(0, max);
    const lastSpace = cut.lastIndexOf(' ');
    head = `${(lastSpace > 0 ? cut.slice(0, lastSpace) : cut).trim()}…`;
  }
  const opens = (head.match(/\(/g) ?? []).length;
  const closes = (head.match(/\)/g) ?? []).length;
  return opens > closes ? head + ')'.repeat(opens - closes) : head;
}

/**
 * The agent's entry map: what exists, how much of it, and where to start. Every
 * cold session reads this first, so it stays one-liners and pointers.
 */
export function generateMap(
  snapshot: GraphSnapshot,
  taxonomy: TaxonomyRow[],
): string {
  const lines: string[] = [
    '# MAP — what is in this repo and where',
    '',
    '<!-- Generated by `sidekick graph map`. Do not edit by hand: regenerate. -->',
    '',
    stamp(snapshot),
    '',
    '**Retrieval ordering:** read this map → query the graph (`bun bin/cli.ts graph query|coverage|gaps|applies|diff`) → grep only when both miss.',
    '',
    'Current state is [docs/STATE.md](docs/STATE.md). This file says what exists; that one says where it stands.',
    '',
  ];

  if (taxonomy.length > 0) {
    lines.push(
      '## Folders',
      '',
      '| Path | Meaning | Lifecycle |',
      '|---|---|---|',
      ...taxonomy.map((t) => `| ${t.folder} | ${t.meaning} | ${t.lifecycle} |`),
      '',
    );
  }

  const epics = entitiesOf(snapshot, 'epic');
  if (epics.length > 0) {
    lines.push(`## Work — ${epics.length} epic(s)`, '');
    for (const epic of epics) {
      const items = itemsOfEpic(snapshot, epic.id);
      const done = items.filter((i) => i.status === 'done').length;
      lines.push(
        `- \`${epic.id}\` — ${epic.title} · ${done}/${items.length} items done → [${epic.path}](${epic.path})`,
      );
    }
    lines.push('');
  }

  const adrs = entitiesOf(snapshot, 'adr');
  lines.push(`## Decisions — ${adrs.length} ADR(s)`, '');
  const byStatus = new Map<string, Entity[]>();
  for (const adr of adrs) {
    const status = adr.status ?? 'unknown';
    byStatus.set(status, [...(byStatus.get(status) ?? []), adr]);
  }
  for (const status of [...byStatus.keys()].sort()) {
    lines.push(`**${status}:**`);
    for (const adr of byStatus.get(status) ?? []) {
      lines.push(`- \`${adr.id}\` — ${adr.title} → [${adr.path}](${adr.path})`);
    }
    lines.push('');
  }

  const research = entitiesOf(snapshot, 'research');
  lines.push(`## Research — ${research.length} topic(s)`, '');
  for (const topic of research) {
    lines.push(
      `- \`${topic.id.replace('research:', '')}\` — ${topic.title} → [${topic.path}](${topic.path})`,
    );
  }
  lines.push('');

  const suites = entitiesOf(snapshot, 'suite');
  const measures = snapshot.edges.filter(
    (e) => e.rel === 'measures' && e.src.startsWith('case:'),
  );
  lines.push(`## Eval suites — ${suites.length}`, '');
  for (const suite of suites) {
    const name = suite.id.replace('suite:', '');
    const cases = measures.filter((e) => e.src.startsWith(`case:${name}/`));
    const subjects = [...new Set(cases.map((e) => e.dst))].sort();
    lines.push(
      `- \`${name}\` — ${cases.length} case(s) → ${subjects.join(', ') || 'no subject'}`,
    );
  }
  lines.push('');

  for (const [kind, heading] of [
    ['agent', 'Agents'],
    ['skill', 'Skills'],
    ['helper', 'CLI helpers'],
  ] as const) {
    const items = entitiesOf(snapshot, kind);
    lines.push(`## ${heading} — ${items.length}`, '');
    for (const item of items) {
      const name = item.id.split(':')[1];
      // Helpers without a leading block comment have no authored one-liner;
      // repeating the name as its own description says nothing twice.
      lines.push(
        item.title === name ? `- \`${name}\`` : `- \`${name}\` — ${item.title}`,
      );
    }
    lines.push('');
  }

  const steering = snapshot.entities
    .filter(
      (e) =>
        e.kind === 'doc' &&
        e.path !== null &&
        /^(docs\/[A-Z-]+\.md|AGENTS\.md|README\.md)$/.test(e.path),
    )
    .sort(byId);
  if (steering.length > 0) {
    lines.push('## Steering docs', '');
    for (const doc of steering) {
      lines.push(`- [${doc.path}](${doc.path}) — ${doc.title}`);
    }
    lines.push('');
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

