/**
 * Regenerate both surfaces from the live tree. Returned rather than written, so
 * the drift check and the writer share one code path and cannot disagree about
 * what "regenerated" means.
 */
export function renderSurfaces(repoRoot: string): {
  state: string;
  map: string;
} {
  const { snapshot } = collectGraph(repoRoot);
  const summary = lintSummary(collectSourceLint(repoRoot));
  const readmePath = path.join(repoRoot, 'docs/README.md');
  const taxonomy = fs.existsSync(readmePath)
    ? parseTaxonomy(fs.readFileSync(readmePath, 'utf-8'))
    : [];
  return {
    state: generateState({ snapshot, lint: summary }),
    map: generateMap(snapshot, taxonomy),
  };
}

export interface GenerateCliResult {
  stdout: string;
  exitCode: number;
}

/** Write one surface and report whether the write changed anything. */
export function runGenerateCli(
  repoRoot: string,
  which: 'state' | 'map',
  json: boolean,
): GenerateCliResult {
  const rendered = renderSurfaces(repoRoot);
  const relPath = which === 'state' ? STATE_PATH : MAP_PATH;
  const content = which === 'state' ? rendered.state : rendered.map;
  const abs = path.join(repoRoot, relPath);
  const before = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf-8') : null;
  const changed =
    before === null || normalizeForDrift(before) !== normalizeForDrift(content);

  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);

  const lineCount = content.split('\n').length;
  if (json) {
    return {
      stdout: JSON.stringify(
        { path: relPath, lines: lineCount, changed },
        null,
        2,
      ),
      exitCode: 0,
    };
  }
  return {
    stdout: `wrote ${relPath} (${lineCount} lines)${changed ? '' : ' — unchanged'}`,
    exitCode: 0,
  };
}
